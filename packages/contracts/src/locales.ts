export function translateError(locale: Locale, code: string) {
  return (
    errors[locale][code as keyof typeof errors.en] ??
    errors[locale].INTERNAL_ERROR
  );
}
export function isLocale(value: string): value is Locale {
  return value === "en" || value === "fa";
}
export function resolveLocale(
  explicit: string | undefined,
  saved: string | undefined,
  cookie: string | undefined,
  browser: string | undefined,
): Locale {
  for (const value of [explicit, saved, cookie])
    if (value && isLocale(value)) return value;
  const candidates = (browser ?? "")
    .split(",")
    .map((part) => {
      const [tag, q] = part.trim().split(";q=");
      return {
        tag: tag.toLowerCase().split("-")[0],
        q: q === undefined ? 1 : Number(q),
      };
    })
    .filter((x) => x.q > 0 && Number.isFinite(x.q))
    .sort((a, b) => b.q - a.q);
  return (candidates.find((x) => isLocale(x.tag))?.tag as Locale) ?? "en";
}
